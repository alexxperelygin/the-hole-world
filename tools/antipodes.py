def ocean(lat, lon):
    if lat < -60: return "~SOU"
    if lat > 66: return "~ARC"
    if 20 <= lon <= 147 and lat <= 25:
        return "~PAC" if (lon > 100 and lat > -10) else "~IND"
    if -70 <= lon < 20: return "~ATL"
    if -100 < lon < -70 and lat > 8: return "~ATL"
    return "~PAC"
